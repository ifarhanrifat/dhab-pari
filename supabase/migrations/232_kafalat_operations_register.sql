-- ═════════════════════════════════════════════════════════════════════════
-- Transport and pocket money — monthly, for as long as the child is active
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS kafalat_disbursements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  child_id uuid NOT NULL REFERENCES kafalat_children(id) ON DELETE CASCADE,
  category varchar NOT NULL CHECK (category IN ('transport', 'pocket_money')),
  month date NOT NULL,
  amount_pkr decimal NOT NULL CHECK (amount_pkr > 0),
  status varchar NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled', 'paid', 'skipped')),
  -- Who the money actually goes to. Transport is usually the driver, though a
  -- guardian who does the school run themselves is paid the same way; pocket
  -- money is always the guardian.
  recipient varchar NOT NULL DEFAULT 'guardian' CHECK (recipient IN ('guardian', 'driver', 'student')),
  driver_name varchar,
  paid_on date,
  method varchar CHECK (method IN ('cash', 'bank', 'jazzcash', 'easypaisa')),
  -- The paper record of a signature, not a digital one — same convention as
  -- the uniform table above.
  signed_by varchar,
  signed_note text,
  voucher_id uuid REFERENCES vouchers(id) ON DELETE SET NULL,
  skipped_reason text,
  created_at timestamptz DEFAULT now(),
  UNIQUE (child_id, category, month)
);

CREATE INDEX IF NOT EXISTS kafalat_disbursements_status_idx ON kafalat_disbursements(status, month);

-- Raises this month's transport and pocket-money lines for every active
-- child who has them in their package, the same idempotent shape as
-- sadqa_upkeep_run() and pool_announce_recurring_month().
CREATE OR REPLACE FUNCTION kafalat_disbursement_run() RETURNS jsonb AS $$
DECLARE v_month date; v_year varchar; v_count int;
BEGIN
  v_month := date_trunc('month', (now() AT TIME ZONE 'Asia/Karachi')::date)::date;
  v_year := kafalat_current_year();

  INSERT INTO kafalat_disbursements (child_id, category, month, amount_pkr, recipient)
  SELECT c.id, l.category, v_month, round(l.annual_amount_pkr / 12.0),
         CASE WHEN l.category = 'transport' THEN 'driver' ELSE 'guardian' END
    FROM kafalat_children c
    JOIN kafalat_package_lines l ON l.child_id = c.id AND l.academic_year = v_year
   WHERE c.status = 'active'
     AND l.category IN ('transport', 'pocket_money')
     AND l.annual_amount_pkr > 0
     AND NOT EXISTS (SELECT 1 FROM kafalat_disbursements d
                      WHERE d.child_id = c.id AND d.category = l.category AND d.month = v_month);
  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN jsonb_build_object('created', v_count, 'month', v_month);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION kafalat_disbursement_run() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION kafalat_disbursement_run() TO authenticated;

DO $$
BEGIN
  PERFORM cron.schedule('kafalat-disbursement-run', '10 4 * * *', 'SELECT kafalat_disbursement_run()');
  RAISE NOTICE 'pg_cron: kafalat transport/pocket-money lines raised daily at 09:10 PKT';
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'pg_cron unavailable — run kafalat_disbursement_run() from the Kafalat screen. %', SQLERRM;
END $$;

CREATE OR REPLACE FUNCTION kafalat_pay_disbursement(
  p_disbursement_id uuid, p_method varchar, p_signed_by varchar DEFAULT NULL,
  p_driver_name varchar DEFAULT NULL, p_signed_note text DEFAULT NULL
) RETURNS jsonb AS $$
DECLARE
  d kafalat_disbursements%ROWTYPE; c kafalat_children%ROWTYPE;
  v_cash uuid; v_voucher_id uuid; v_voucher_no varchar;
BEGIN
  IF NOT COALESCE(current_admin_permission('post_transactions'), false) THEN
    RAISE EXCEPTION 'Not authorized' USING ERRCODE = 'P0001';
  END IF;
  SELECT * INTO d FROM kafalat_disbursements WHERE id = p_disbursement_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Not found' USING ERRCODE = 'P0001'; END IF;
  IF d.status <> 'scheduled' THEN
    RAISE EXCEPTION 'This is already %.', d.status USING ERRCODE = 'P0001';
  END IF;
  IF d.category = 'transport' AND COALESCE(trim(p_driver_name), '') = '' THEN
    RAISE EXCEPTION 'Name the driver this transport payment is going to.' USING ERRCODE = 'P0001';
  END IF;
  SELECT * INTO c FROM kafalat_children WHERE id = d.child_id;

  SELECT id INTO v_cash FROM accounts WHERE system = 'donors_projects'
     AND code = (CASE WHEN p_method = 'cash' THEN 'DP-1001' ELSE 'DP-1002' END);

  INSERT INTO vouchers (system, voucher_type, voucher_date, particular, amount_pkr,
    from_account_id, to_account_id, party_name, kafalat_child_id, fund_type)
  VALUES ('donors_projects', 'kafalat_payment', (now() AT TIME ZONE 'Asia/Karachi')::date,
    c.first_name || ' (' || c.code || ') — ' || d.category || ' · ' || to_char(d.month, 'Mon YYYY')
      || CASE WHEN d.category = 'transport' THEN ' · driver ' || p_driver_name ELSE '' END,
    d.amount_pkr, v_cash, v_cash,
    CASE WHEN d.category = 'transport' THEN p_driver_name ELSE c.guardian_name END,
    d.child_id, 'kafalat')
  RETURNING id, voucher_no INTO v_voucher_id, v_voucher_no;

  UPDATE kafalat_disbursements
     SET status = 'paid', paid_on = (now() AT TIME ZONE 'Asia/Karachi')::date, method = p_method,
         signed_by = p_signed_by, driver_name = COALESCE(p_driver_name, driver_name),
         signed_note = p_signed_note, voucher_id = v_voucher_id
   WHERE id = p_disbursement_id;

  RETURN jsonb_build_object('voucher_no', v_voucher_no, 'amount', d.amount_pkr);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION kafalat_pay_disbursement(uuid, varchar, varchar, varchar, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION kafalat_pay_disbursement(uuid, varchar, varchar, varchar, text) TO authenticated;

