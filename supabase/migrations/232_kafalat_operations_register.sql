-- Migration 232: the paper the committee actually hands to a school and a
-- driver — roll numbers, uniforms, transport, and the disbursements that pay
-- for them.
--
-- ═════════════════════════════════════════════════════════════════════════
-- What this adds, and what it deliberately leaves alone
-- ═════════════════════════════════════════════════════════════════════════
-- The measuring account (migration 230) answers "how much do we still need
-- this year, and from how many donors". It never answers "which school, which
-- roll number, has this term's uniform gone out yet" — that is a different
-- axis of the same programme, and it is what a committee member actually
-- carries to a school gate or hands to a driver.
--
-- Two disbursement rhythms, because they are genuinely different:
--
--   Uniform — twice a year, not monthly. The committee decides per child
--   whether both go out together at the start of the year, staggered six
--   months apart (a growing child, a uniform that is still whole in March),
--   or paid as cash directly to the guardian, who buys it themselves. The
--   schedule is generated once, at approval, from that choice.
--
--   Transport and pocket money — monthly, for as long as the child is
--   active, generated by a scheduled job the same way sadqa_upkeep_run() and
--   pool_announce_recurring_month() already generate theirs.
--
-- Both post through the 'kafalat_payment' voucher type migration 218 already
-- reserved for exactly this and never used — the ring-fencing, the numbering,
-- the per-child subsidiary ledger (ensure_kafalat_child_account) were all
-- already built, waiting for a real caller. This is deliberately a SEPARATE
-- ledger dimension from the measuring account: the measuring account tracks
-- whether donors have raised enough; this tracks what was actually spent on
-- one named child. A committee should be able to answer both "are we short
-- this year" and "what has Bilal actually received" without one figure
-- standing in for the other.

ALTER TABLE kafalat_children
  ADD COLUMN IF NOT EXISTS roll_no varchar,
  ADD COLUMN IF NOT EXISTS section varchar,
  -- both       — two uniforms handed over together, once, at the start
  -- staggered  — one now, the second six months later
  -- cash       — money to the guardian instead of a physical item; they buy it
  ADD COLUMN IF NOT EXISTS uniform_mode varchar NOT NULL DEFAULT 'staggered'
    CHECK (uniform_mode IN ('both', 'staggered', 'cash'));

-- ═════════════════════════════════════════════════════════════════════════
-- Uniforms
-- ═════════════════════════════════════════════════════════════════════════
CREATE TABLE IF NOT EXISTS kafalat_uniform_issues (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  child_id uuid NOT NULL REFERENCES kafalat_children(id) ON DELETE CASCADE,
  academic_year varchar NOT NULL,
  -- 1 or 2 — which of the year's two uniforms this is.
  issue_no int NOT NULL CHECK (issue_no IN (1, 2)),
  scheduled_on date NOT NULL,
  amount_pkr decimal NOT NULL DEFAULT 0 CHECK (amount_pkr >= 0),
  status varchar NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled', 'issued', 'skipped')),
  issued_on date,
  -- A physical item at the school gate, or cash into the guardian's hand —
  -- either way, somebody's name goes down as having received it. Not a
  -- digital signature; a record that the paper form was signed, the same
  -- convention this codebase already uses for verifiers (co_verifier_names).
  received_by varchar,
  signed_note text,
  voucher_id uuid REFERENCES vouchers(id) ON DELETE SET NULL,
  skipped_reason text,
  created_at timestamptz DEFAULT now(),
  UNIQUE (child_id, academic_year, issue_no)
);

CREATE INDEX IF NOT EXISTS kafalat_uniform_status_idx ON kafalat_uniform_issues(status, scheduled_on);

-- Built once, at approval, from the committee's choice for this child. Not a
-- scheduled job — a child does not get a new uniform schedule every day, only
-- once a year (and kafalat_approve_child already regenerates the requirement
-- on re-approval, which is the natural place to regenerate this alongside it).
CREATE OR REPLACE FUNCTION kafalat_schedule_uniforms(p_child_id uuid, p_academic_year varchar)
RETURNS void AS $$
DECLARE
  c kafalat_children%ROWTYPE; v_amount decimal; v_start date;
BEGIN
  SELECT * INTO c FROM kafalat_children WHERE id = p_child_id;
  IF NOT FOUND THEN RETURN; END IF;

  SELECT COALESCE(SUM(annual_amount_pkr), 0) / 2 INTO v_amount
    FROM kafalat_package_lines
   WHERE child_id = p_child_id AND academic_year = p_academic_year AND category = 'uniform';
  IF v_amount <= 0 THEN RETURN; END IF;

  v_start := GREATEST(COALESCE(c.joined_on, kafalat_year_starts(p_academic_year)),
                      kafalat_year_starts(p_academic_year));

  -- Regenerating must not lose a uniform that has already gone out — only the
  -- still-scheduled ones are replaced.
  DELETE FROM kafalat_uniform_issues
   WHERE child_id = p_child_id AND academic_year = p_academic_year AND status = 'scheduled';

  IF c.uniform_mode = 'both' THEN
    INSERT INTO kafalat_uniform_issues (child_id, academic_year, issue_no, scheduled_on, amount_pkr)
    VALUES (p_child_id, p_academic_year, 1, v_start, v_amount),
           (p_child_id, p_academic_year, 2, v_start, v_amount)
    ON CONFLICT (child_id, academic_year, issue_no) DO NOTHING;
  ELSE
    -- 'staggered' and 'cash' both run on the same six-month rhythm; 'cash'
    -- only changes how the second half of this function pays it out.
    INSERT INTO kafalat_uniform_issues (child_id, academic_year, issue_no, scheduled_on, amount_pkr)
    VALUES (p_child_id, p_academic_year, 1, v_start, v_amount),
           (p_child_id, p_academic_year, 2, (v_start + interval '6 months')::date, v_amount)
    ON CONFLICT (child_id, academic_year, issue_no) DO NOTHING;
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

GRANT EXECUTE ON FUNCTION kafalat_schedule_uniforms(uuid, varchar) TO authenticated;

-- Folded into approval and re-approval, so the uniform schedule is never a
-- separate step somebody has to remember.
CREATE OR REPLACE FUNCTION kafalat_approve_child(p_child_id uuid) RETURNS jsonb AS $$
DECLARE
  c kafalat_children%ROWTYPE; v_level int; v_min int; v_max int;
  v_year varchar; v_req jsonb; v_this_year decimal;
BEGIN
  IF NOT COALESCE(current_admin_permission('post_transactions'), false) THEN
    RAISE EXCEPTION 'Not authorized' USING ERRCODE = 'P0001';
  END IF;
  SELECT * INTO c FROM kafalat_children WHERE id = p_child_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Child not found' USING ERRCODE = 'P0001'; END IF;
  IF NOT c.guardian_consent_signed THEN
    RAISE EXCEPTION 'Guardian consent has not been signed yet.' USING ERRCODE = 'P0001';
  END IF;

  v_level := class_to_level(c.current_class);
  SELECT value::int INTO v_min FROM site_settings WHERE key = 'kafalat_min_class';
  SELECT value::int INTO v_max FROM site_settings WHERE key = 'kafalat_max_class';
  IF v_level IS NULL OR v_level < COALESCE(v_min, 1) OR v_level > COALESCE(v_max, 10) THEN
    RAISE EXCEPTION
      'Mushtarka Kafalat covers class % to class %. This child''s class (%) is outside that — for a student past class %, Taleemi Wazifa is the right programme.',
      COALESCE(v_min,1), COALESCE(v_max,10), COALESCE(c.current_class, 'not set'), COALESCE(v_max,10)
      USING ERRCODE = 'P0001';
  END IF;

  v_year := kafalat_current_year();

  UPDATE kafalat_children
     SET status = 'active', joined_on = COALESCE(joined_on, (now() AT TIME ZONE 'Asia/Karachi')::date),
         updated_at = now()
   WHERE id = p_child_id;

  v_req := kafalat_generate_requirement(p_child_id, v_year);
  v_this_year := (v_req->>'this_year_requirement')::decimal;

  PERFORM kafalat_post_requirement_delta(v_year, v_this_year,
    c.first_name || ' (' || c.code || ') approved — ' || (v_req->>'months_remaining') || ' months left in ' || v_year,
    p_child_id);

  PERFORM kafalat_schedule_uniforms(p_child_id, v_year);

  RETURN v_req || jsonb_build_object('child_code', c.code);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- Handing one over — a physical item at the school gate, or cash to the
-- guardian if that is what the committee chose for this child.
CREATE OR REPLACE FUNCTION kafalat_issue_uniform(
  p_issue_id uuid, p_received_by varchar, p_signed_note text DEFAULT NULL, p_method varchar DEFAULT 'cash'
) RETURNS jsonb AS $$
DECLARE
  u kafalat_uniform_issues%ROWTYPE; c kafalat_children%ROWTYPE;
  v_cash uuid; v_child_account uuid; v_voucher_id uuid; v_voucher_no varchar;
BEGIN
  IF NOT COALESCE(current_admin_permission('post_transactions'), false) THEN
    RAISE EXCEPTION 'Not authorized' USING ERRCODE = 'P0001';
  END IF;
  SELECT * INTO u FROM kafalat_uniform_issues WHERE id = p_issue_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Not found' USING ERRCODE = 'P0001'; END IF;
  IF u.status <> 'scheduled' THEN
    RAISE EXCEPTION 'This uniform is already %.', u.status USING ERRCODE = 'P0001';
  END IF;
  IF COALESCE(trim(p_received_by), '') = '' THEN
    RAISE EXCEPTION 'Name whoever received it — the child, the guardian, or the shop.'
      USING ERRCODE = 'P0001';
  END IF;
  SELECT * INTO c FROM kafalat_children WHERE id = u.child_id;

  SELECT id INTO v_cash FROM accounts WHERE system = 'donors_projects'
     AND code = (CASE WHEN p_method = 'cash' THEN 'DP-1001' ELSE 'DP-1002' END);

  INSERT INTO vouchers (system, voucher_type, voucher_date, particular, amount_pkr,
    from_account_id, to_account_id, party_name, kafalat_child_id, fund_type)
  VALUES ('donors_projects', 'kafalat_payment', (now() AT TIME ZONE 'Asia/Karachi')::date,
    c.first_name || ' (' || c.code || ') — uniform ' || u.issue_no || '/2, ' || u.academic_year
      || CASE WHEN c.uniform_mode = 'cash' THEN ' (cash to guardian)' ELSE '' END,
    u.amount_pkr, v_cash, v_cash, c.first_name, u.child_id, 'kafalat')
  RETURNING id, voucher_no INTO v_voucher_id, v_voucher_no;

  UPDATE kafalat_uniform_issues
     SET status = 'issued', issued_on = (now() AT TIME ZONE 'Asia/Karachi')::date,
         received_by = p_received_by, signed_note = p_signed_note, voucher_id = v_voucher_id
   WHERE id = p_issue_id;

  RETURN jsonb_build_object('voucher_no', v_voucher_no, 'amount', u.amount_pkr);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION kafalat_issue_uniform(uuid, varchar, text, varchar) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION kafalat_issue_uniform(uuid, varchar, text, varchar) TO authenticated;

