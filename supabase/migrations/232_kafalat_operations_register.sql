-- What is due right now, across both uniforms and monthly disbursements —
-- the one queue the accountant actually works from.
CREATE OR REPLACE FUNCTION kafalat_disbursement_queue() RETURNS jsonb AS $$
  SELECT jsonb_build_object(
    'uniforms', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', u.id, 'child_code', c.code, 'child_name', c.first_name, 'guardian', c.guardian_name,
        'guardian_phone', c.guardian_phone, 'issue_no', u.issue_no, 'scheduled_on', u.scheduled_on,
        'amount', u.amount_pkr, 'uniform_mode', c.uniform_mode
      ) ORDER BY u.scheduled_on)
        FROM kafalat_uniform_issues u JOIN kafalat_children c ON c.id = u.child_id
       WHERE u.status = 'scheduled' AND u.scheduled_on <= (now() AT TIME ZONE 'Asia/Karachi')::date
    ), '[]'::jsonb),
    'disbursements', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'id', d.id, 'child_code', c.code, 'child_name', c.first_name, 'guardian', c.guardian_name,
        'guardian_phone', c.guardian_phone, 'category', d.category, 'month', d.month, 'amount', d.amount_pkr
      ) ORDER BY d.month, d.category)
        FROM kafalat_disbursements d JOIN kafalat_children c ON c.id = d.child_id
       WHERE d.status = 'scheduled'
    ), '[]'::jsonb)
  );
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

REVOKE ALL ON FUNCTION kafalat_disbursement_queue() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION kafalat_disbursement_queue() TO authenticated;

-- ═════════════════════════════════════════════════════════════════════════
-- The register — what a committee member actually prints
-- ═════════════════════════════════════════════════════════════════════════
-- Every active child, their school, roll number, class, fee, when it is next
-- due, and the transport line with a blank for the driver's signature. This
-- is a document meant for paper, not a dashboard — it is built to be printed
-- and carried, the same way the Wazifa verification sheet is.
CREATE OR REPLACE FUNCTION kafalat_register(p_academic_year varchar DEFAULT NULL) RETURNS jsonb AS $$
DECLARE v_year varchar;
BEGIN
  v_year := COALESCE(p_academic_year, kafalat_current_year());
  RETURN jsonb_build_object(
    'academic_year', v_year,
    'generated_at', now(),
    'children', COALESCE((
      SELECT jsonb_agg(jsonb_build_object(
        'code', c.code, 'name', c.first_name, 'guardian', c.guardian_name,
        'guardian_phone', c.guardian_phone, 'roll_no', c.roll_no, 'section', c.section,
        'current_class', c.current_class,
        'school_name', COALESCE(s.name, c.school_name), 'school_location', c.school_location,
        'school_fee_monthly', COALESCE(t.monthly_fee_pkr, 0),
        'fee_annual', COALESCE((SELECT annual_amount_pkr FROM kafalat_package_lines
                                  WHERE child_id = c.id AND academic_year = v_year AND category = 'school_fee'), 0),
        'transport_annual', COALESCE((SELECT annual_amount_pkr FROM kafalat_package_lines
                                       WHERE child_id = c.id AND academic_year = v_year AND category = 'transport'), 0),
        'fee_next_due_on', (date_trunc('month', (now() AT TIME ZONE 'Asia/Karachi')::date)
                             + interval '1 month' - interval '1 day')::date,
        'uniform_mode', c.uniform_mode,
        'uniform_status', (
          SELECT jsonb_agg(jsonb_build_object('issue_no', u.issue_no, 'status', u.status,
                                              'scheduled_on', u.scheduled_on) ORDER BY u.issue_no)
            FROM kafalat_uniform_issues u WHERE u.child_id = c.id AND u.academic_year = v_year
        )
      ) ORDER BY c.code)
        FROM kafalat_children c
        LEFT JOIN schools s ON s.id = c.school_id
        LEFT JOIN school_fee_tiers t ON t.school_id = c.school_id
          AND class_to_level(c.current_class) BETWEEN t.class_from AND t.class_to
       WHERE c.status = 'active'
    ), '[]'::jsonb)
  );
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public;

GRANT EXECUTE ON FUNCTION kafalat_register(varchar) TO authenticated;

