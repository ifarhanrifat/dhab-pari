-- ═════════════════════════════════════════════════════════════════════════
-- Fixing a collision waiting to happen: ensure_kafalat_child_account()
-- ═════════════════════════════════════════════════════════════════════════
-- migration 218 built this and nothing had ever called it — kafalat_payment
-- vouchers were reserved but unused until this migration wires real uniform
-- and disbursement payments through them. Driving it for the first time
-- surfaced the bug: the account code was built from the first eight hex
-- characters of the child's UUID —
--
--     'KID-' || substr(replace(p_child_id::text, '-', ''), 1, 8)
--
-- — thirty-two bits of a randomly generated identifier, while the function
-- had already fetched the child's real code (kafalat_children.code, unique
-- by a real sequence, next_kafalat_code()) into a variable and used it only
-- for the account's display NAME. Two children's UUIDs sharing their first
-- eight hex characters produce the same account code and the second child's
-- INSERT fails outright — accounts.code is unique. Confirmed empirically: a
-- handful of test children were enough to collide.
--
-- No live data is affected — nothing had posted a kafalat_payment voucher
-- before this migration, so no 'KID-' account exists yet to repair.
CREATE OR REPLACE FUNCTION ensure_kafalat_child_account(p_child_id uuid) RETURNS uuid AS $$
DECLARE v_id uuid; v_code varchar;
BEGIN
  SELECT id INTO v_id FROM accounts WHERE kafalat_child_id = p_child_id;
  IF v_id IS NOT NULL THEN RETURN v_id; END IF;
  SELECT code INTO v_code FROM kafalat_children WHERE id = p_child_id;
  INSERT INTO accounts (code, name, type, system, kafalat_child_id, opening_balance)
  VALUES ('KID-' || COALESCE(v_code, replace(p_child_id::text, '-', '')),
          COALESCE(v_code, 'Child'), 'student', 'donors_projects', p_child_id, 0)
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

GRANT EXECUTE ON FUNCTION ensure_kafalat_child_account(uuid) TO authenticated;
