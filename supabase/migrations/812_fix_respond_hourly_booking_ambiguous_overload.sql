-- Migration 812: real bug, 2026-11-05 — "sent an hourly booking request,
-- driver tries to accept, 'something went wrong'." Root cause: migration
-- 787 introduced respond_hourly_booking(uuid, boolean) for the new
-- broadcast-dispatch model, but never dropped the earlier
-- respond_hourly_booking(uuid, boolean, text DEFAULT NULL) from 711 first.
-- Postgres treats different argument-type lists as different functions, so
-- CREATE OR REPLACE in 787 didn't replace the old one — it added a second,
-- overloaded function of the same name. Since the 3rd arg has a DEFAULT,
-- both signatures are valid candidates for a call with just
-- {p_booking_id, p_accept}, which PostgREST can't disambiguate (error
-- PGRST203). That raw "Could not choose the best candidate function..."
-- message gets classified as machine-generated by friendlyError() (it
-- contains "function ") and replaced with the generic "Something went
-- wrong" toast — matching the reported symptom exactly, on every accept
-- AND every decline, for every hourly booking.
--
-- Fix: drop the stale 3-arg overload. The 2-arg version (787, carried
-- forward unchanged since) is the correct, current definition and is left
-- in place.

DROP FUNCTION IF EXISTS respond_hourly_booking(uuid, boolean, text);
