-- Migration 764: PIN-verified start + the real embedded bilateral map,
-- unified into one popup instead of scattered pages and an external map.
--
-- Real ask, 2026-10-28 (right after 763 fixed the gating/live-share
-- bugs): "we already have a ride sharing embedded map in the
-- application working... keep remaining in the app, navigate to the
-- rider place, when reached to that spot the rider will give code to
-- driver... vehicle will start and finish the ride on that embedded
-- popup screen." Two real things already existed, fully built, but
-- disconnected from ride-dispatch:
--
--   1. vehicle_trip_locations / ping_trip_location (400) — a genuine
--      BILATERAL live map (both parties ping their own GPS, poll the
--      other's) already used by /portal/marketplace/trip/[bookingId]
--      for both driver and rider. The driver just never had a reason
--      to open that page — 763's own fix routed the driver to
--      my-vehicle/trips's different, ONE-WAY, opt-in
--      vehicle_trip_offer_locations toggle instead, which is the wrong
--      mechanism for a 1:1 ride-dispatch accept.
--   2. The 4-digit PIN-verified start, already built for hourly/
--      equipment (652) — never extended to trip bookings, which is
--      exactly the "driver has no idea who's getting in" case it's
--      most needed for.
--
-- pin is only ever generated by accept_ride_dispatch below — every
-- other vehicle_trip_bookings creation path (ordinary trip-share route
-- bookings) leaves it NULL, same backward-compat pattern 652 already
-- uses: start_trip_booking only enforces the PIN when one exists, so
-- existing/other booking types just skip the gate entirely, unaffected.

ALTER TABLE vehicle_trip_bookings ADD COLUMN IF NOT EXISTS pin varchar(4);
ALTER TABLE vehicle_trip_bookings ADD COLUMN IF NOT EXISTS started_at timestamptz;
-- Same realtime-publication step 726/753 already did for other booking
-- tables — the popup's start/complete transitions should land instantly
-- for whichever party didn't just tap the button, not wait for a poll.
ALTER PUBLICATION supabase_realtime ADD TABLE vehicle_trip_bookings;
ALTER TABLE vehicle_trip_bookings DROP CONSTRAINT IF EXISTS vehicle_trip_bookings_status_check;
ALTER TABLE vehicle_trip_bookings ADD CONSTRAINT vehicle_trip_bookings_status_check
  CHECK (status IN ('confirmed', 'in_progress', 'completed', 'cancelled'));

-- Identical to 763's version, plus a pickup PIN on the new booking.
CREATE OR REPLACE FUNCTION accept_ride_dispatch(p_request_id uuid) RETURNS uuid AS $$
DECLARE
  v_portal_user_id uuid := current_portal_user_id();
  r ride_dispatch_requests%ROWTYPE; v vehicles%ROWTYPE; v_cat vehicle_categories%ROWTYPE;
  v_initiator_tenant_id uuid;
  v_in_city boolean; v_village_lat decimal; v_village_lng decimal; v_village_detour decimal; v_fare decimal; v_tier varchar;
  v_reference_village_fare decimal;
  v_trip_offer_id uuid; v_fare_offer_id uuid;
BEGIN
  SELECT * INTO r FROM ride_dispatch_requests WHERE id = p_request_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Request not found.' USING ERRCODE = 'P0001'; END IF;
  IF r.status != 'open' THEN RAISE EXCEPTION 'Someone else already accepted this ride.' USING ERRCODE = 'P0001'; END IF;

  SELECT tenant_id INTO v_initiator_tenant_id FROM portal_users WHERE id = r.initiator_portal_user_id;

  SELECT v2.* INTO v FROM vehicles v2
  WHERE v2.portal_user_id = v_portal_user_id AND v2.is_active
    AND (NOT r.is_out_of_city OR v2.allows_out_of_city)
    AND (
      (v2.category_id = ANY(r.category_ids) AND (NOT r.is_out_of_city OR EXISTS (SELECT 1 FROM vehicle_categories WHERE id = v2.category_id AND out_of_city_eligible)))
      OR EXISTS (
        SELECT 1 FROM vehicle_categories vc_mine, vehicle_categories vc_req
        WHERE vc_mine.id = v2.category_id AND vc_req.id = r.category_id AND vc_mine.key = vc_req.key
          AND (NOT r.is_out_of_city OR vc_mine.out_of_city_eligible)
          AND EXISTS (
            SELECT 1 FROM marketplace_share_agreements sa
            WHERE sa.owner_tenant_id = v2.tenant_id AND sa.target_tenant_id = v_initiator_tenant_id
              AND sa.category = 'ride_dispatch' AND sa.is_active
          )
      )
    )
  ORDER BY (v2.category_id = ANY(r.category_ids)) DESC
  LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'This ride is not for your vehicle category.' USING ERRCODE = 'P0001'; END IF;

  SELECT * INTO v_cat FROM vehicle_categories WHERE id = v.category_id;

  v_in_city := v.is_online AND v.current_lat IS NOT NULL
    AND v.current_location_updated_at > now() - interval '30 minutes'
    AND haversine_km(v.current_lat, v.current_lng, r.pickup_lat, r.pickup_lng) <= 6;

  SELECT center_lat, center_lng INTO v_village_lat, v_village_lng
  FROM tenant_service_zones WHERE tenant_id = v.tenant_id AND zone_kind = 'village' AND is_active LIMIT 1;
  IF v_village_lat IS NULL THEN
    SELECT lat, lng INTO v_village_lat, v_village_lng FROM cities WHERE is_home_city LIMIT 1;
  END IF;
  v_village_detour := CASE WHEN v_village_lat IS NOT NULL
    THEN round(v_cat.per_km_pkr * haversine_km(v_village_lat, v_village_lng, r.pickup_lat, r.pickup_lng) * 2)
    ELSE 0 END;
  v_reference_village_fare := round(v_cat.base_fare_pkr + v_cat.per_km_pkr * r.distance_km) + v_village_detour;

  IF v_in_city THEN
    v_fare := round(v_cat.base_fare_pkr + v_cat.per_km_pkr * r.distance_km);
    v_tier := CASE WHEN v.tenant_id = v_initiator_tenant_id THEN 'in_city' ELSE 'cross_tenant_in_city' END;
  ELSE
    v_fare := v_reference_village_fare;
    v_tier := CASE WHEN v.tenant_id = v_initiator_tenant_id THEN 'in_village' ELSE 'cross_tenant_in_village' END;
  END IF;

  -- Same dedup set_trip_offer_live_sharing (414) already uses: only one
  -- live-shared offer per vehicle at a time.
  UPDATE vehicle_trip_offers SET share_live_location = false WHERE vehicle_id = v.id AND share_live_location;
  DELETE FROM vehicle_trip_offer_locations WHERE trip_offer_id IN (SELECT id FROM vehicle_trip_offers WHERE vehicle_id = v.id);

  INSERT INTO vehicle_trip_offers (vehicle_id, origin, destination, classification, travel_date, seats_available, listed_fare_per_seat_pkr, trip_type, status, dest_lat, dest_lng, distance_km, share_live_location, live_location_started_at)
  VALUES (v.id, r.pickup_label, r.dropoff_label, 'intercity', (now() AT TIME ZONE 'Asia/Karachi')::date, 1, v_fare, 'oneway', 'closed', r.dropoff_lat, r.dropoff_lng, r.distance_km, true, now())
  RETURNING id INTO v_trip_offer_id;

  INSERT INTO vehicle_trip_fare_offers (trip_offer_id, portal_user_id, seats_requested, proposed_fare_per_seat_pkr, status, responded_at)
  VALUES (v_trip_offer_id, r.initiator_portal_user_id, 1, v_fare, 'accepted', now())
  RETURNING id INTO v_fare_offer_id;

  INSERT INTO vehicle_trip_bookings (trip_offer_id, fare_offer_id, vehicle_id, portal_user_id, seats, agreed_fare_per_seat_pkr, total_amount_pkr, leg, pin)
  VALUES (v_trip_offer_id, v_fare_offer_id, v.id, r.initiator_portal_user_id, 1, v_fare, v_fare, 'oneway', lpad(floor(random() * 10000)::text, 4, '0'));

  UPDATE ride_dispatch_requests SET status = 'accepted', accepted_vehicle_id = v.id, trip_offer_id = v_trip_offer_id,
    accepted_at = now(), fare_pkr = v_fare, matched_tenant_id = v.tenant_id, tier_used = v_tier, reference_village_fare_pkr = v_reference_village_fare
  WHERE id = p_request_id;

  INSERT INTO portal_notifications (portal_user_id, event_type, title, body, link)
  VALUES (r.initiator_portal_user_id, 'ride_dispatch_accepted', 'A driver accepted your ride',
    v.owner_name || ' (' || v.vehicle_type || COALESCE(' · ' || v.vehicle_number, '') || ') is on the way — Rs ' || v_fare::text,
    '/portal/marketplace/ride-dispatch/' || p_request_id);

  RETURN v_trip_offer_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- Start, PIN-gated the same way start_hourly_trip/start_equipment_job
-- (652) already are. A booking with no pin (every non-ride-dispatch
-- booking type today) just skips the check entirely.
DROP FUNCTION IF EXISTS start_trip_booking(uuid, varchar);
CREATE OR REPLACE FUNCTION start_trip_booking(p_trip_booking_id uuid, p_pin varchar DEFAULT NULL) RETURNS void AS $$
DECLARE b vehicle_trip_bookings%ROWTYPE; v vehicles%ROWTYPE;
BEGIN
  SELECT * INTO b FROM vehicle_trip_bookings WHERE id = p_trip_booking_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found.' USING ERRCODE = 'P0001'; END IF;
  SELECT * INTO v FROM vehicles WHERE id = b.vehicle_id;
  IF NOT (COALESCE(current_admin_permission('manage_parties'), false) OR v.portal_user_id = current_portal_user_id()) THEN
    RAISE EXCEPTION 'You do not manage this vehicle.' USING ERRCODE = 'P0001';
  END IF;
  IF b.status <> 'confirmed' THEN RAISE EXCEPTION 'This trip is not ready to start.' USING ERRCODE = 'P0001'; END IF;
  IF b.pin IS NOT NULL AND trim(COALESCE(p_pin, '')) <> b.pin THEN
    RAISE EXCEPTION 'Incorrect code — ask the rider for the 4-digit code shown in their app.' USING ERRCODE = 'P0001';
  END IF;
  UPDATE vehicle_trip_bookings SET status = 'in_progress', started_at = now() WHERE id = p_trip_booking_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;
REVOKE ALL ON FUNCTION start_trip_booking(uuid, varchar) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION start_trip_booking(uuid, varchar) TO authenticated;

-- Same as before, now also accepts a trip that was started (not just one
-- still sitting at 'confirmed') — a booking that never goes through the
-- PIN step (every non-ride-dispatch type, unchanged) behaves exactly as
-- it always did.
CREATE OR REPLACE FUNCTION complete_trip_booking(p_trip_booking_id uuid) RETURNS jsonb AS $$
DECLARE
  b vehicle_trip_bookings%ROWTYPE; v vehicles%ROWTYPE; o vehicle_trip_offers%ROWTYPE;
  v_vehicle_account uuid; v_commission_account uuid; v_commission_pct decimal; v_commission_amount decimal := 0;
  v_commission_voucher_id uuid;
BEGIN
  SELECT * INTO b FROM vehicle_trip_bookings WHERE id = p_trip_booking_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Booking not found' USING ERRCODE = 'P0001'; END IF;
  IF b.status NOT IN ('confirmed', 'in_progress') THEN RAISE EXCEPTION 'This trip is not awaiting completion.' USING ERRCODE = 'P0001'; END IF;
  SELECT * INTO v FROM vehicles WHERE id = b.vehicle_id;
  SELECT * INTO o FROM vehicle_trip_offers WHERE id = b.trip_offer_id;
  IF v.portal_user_id IS DISTINCT FROM current_portal_user_id() AND NOT COALESCE(current_admin_permission('post_transactions'), false) THEN
    RAISE EXCEPTION 'Not authorized' USING ERRCODE = 'P0001';
  END IF;

  UPDATE vehicle_trip_bookings SET status = 'completed', completed_at = now() WHERE id = p_trip_booking_id;

  IF v.commission_mode = 'per_order' THEN
    v_vehicle_account := ensure_vehicle_account(v.id);
    SELECT id INTO v_commission_account FROM accounts WHERE system = 'donors_projects' AND code = 'DP-4050';
    v_commission_pct := vehicle_commission_pct(v.vehicle_type, o.classification);
    v_commission_amount := round(b.total_amount_pkr * v_commission_pct / 100, 2);
    IF v_commission_amount > 0 THEN
      INSERT INTO vouchers (system, voucher_type, voucher_date, particular, amount_pkr, from_account_id, to_account_id, party_name)
      VALUES ('donors_projects', 'income', (now() AT TIME ZONE 'Asia/Karachi')::date,
        'Marketplace commission — ' || o.origin || ' → ' || o.destination || ' return trip (paid directly to driver)', v_commission_amount, v_commission_account, v_vehicle_account, v.owner_name)
      RETURNING id INTO v_commission_voucher_id;
      UPDATE vehicle_trip_bookings SET commission_voucher_id = v_commission_voucher_id WHERE id = p_trip_booking_id;
    END IF;
    PERFORM check_seller_balance_notify('vehicle', v.id);
  END IF;

  RETURN jsonb_build_object('amount', b.total_amount_pkr, 'commission', v_commission_amount);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- The bilateral map must keep working while a trip is 'in_progress' too,
-- not just 'confirmed' — a driver who already started the ride is still
-- very much travelling with the rider onboard.
CREATE OR REPLACE FUNCTION ping_trip_location(p_trip_booking_id uuid, p_lat decimal, p_lng decimal) RETURNS void AS $$
DECLARE v_portal_user_id uuid := current_portal_user_id(); b vehicle_trip_bookings%ROWTYPE; v_role varchar;
BEGIN
  SELECT * INTO b FROM vehicle_trip_bookings WHERE id = p_trip_booking_id;
  IF NOT FOUND OR b.status NOT IN ('confirmed', 'in_progress') THEN RAISE EXCEPTION 'This trip is not active.' USING ERRCODE = 'P0001'; END IF;

  IF b.portal_user_id = v_portal_user_id THEN v_role := 'rider';
  ELSIF EXISTS (SELECT 1 FROM vehicles WHERE id = b.vehicle_id AND portal_user_id = v_portal_user_id) THEN v_role := 'driver';
  ELSE RAISE EXCEPTION 'You are not part of this trip.' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO vehicle_trip_locations (trip_booking_id, role, lat, lng, updated_at)
  VALUES (p_trip_booking_id, v_role, p_lat, p_lng, now())
  ON CONFLICT (trip_booking_id, role) DO UPDATE SET lat = p_lat, lng = p_lng, updated_at = now();
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- Single read for the shared ride-lifecycle popup — resolves the
-- caller's own role and only ever includes `pin` in the rider's own
-- copy (same discipline 652's comment requires: a driver must never be
-- able to read it off the network response, only hear it from the
-- rider in person). vehicle_trip_offers has no pickup coordinates of
-- its own (only dest_lat/dest_lng) — a ride-dispatch booking's real
-- pickup point only lives on its own ride_dispatch_requests row.
CREATE OR REPLACE FUNCTION trip_booking_lifecycle_detail(p_trip_booking_id uuid) RETURNS jsonb AS $$
DECLARE
  b vehicle_trip_bookings%ROWTYPE; o vehicle_trip_offers%ROWTYPE; v vehicles%ROWTYPE;
  v_portal_user_id uuid := current_portal_user_id();
  v_role varchar; v_pickup_lat decimal; v_pickup_lng decimal; v_pickup_label text;
BEGIN
  SELECT * INTO b FROM vehicle_trip_bookings WHERE id = p_trip_booking_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
  SELECT * INTO o FROM vehicle_trip_offers WHERE id = b.trip_offer_id;
  SELECT * INTO v FROM vehicles WHERE id = b.vehicle_id;

  IF b.portal_user_id = v_portal_user_id THEN v_role := 'rider';
  ELSIF v.portal_user_id = v_portal_user_id THEN v_role := 'driver';
  ELSE RETURN NULL;
  END IF;

  SELECT pickup_lat, pickup_lng, pickup_label INTO v_pickup_lat, v_pickup_lng, v_pickup_label
  FROM ride_dispatch_requests WHERE trip_offer_id = b.trip_offer_id;

  RETURN jsonb_build_object(
    'booking_id', b.id, 'role', v_role, 'status', b.status, 'trip_offer_id', b.trip_offer_id,
    'origin', o.origin, 'origin_ur', o.origin_ur, 'destination', o.destination, 'destination_ur', o.destination_ur,
    'pickup_lat', v_pickup_lat, 'pickup_lng', v_pickup_lng, 'pickup_label', v_pickup_label,
    'dest_lat', o.dest_lat, 'dest_lng', o.dest_lng,
    'pin', CASE WHEN v_role = 'rider' THEN b.pin ELSE NULL END
  );
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public;
REVOKE ALL ON FUNCTION trip_booking_lifecycle_detail(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION trip_booking_lifecycle_detail(uuid) TO authenticated;

-- my_ongoing_ride (745, widened in 763) now also hands back a
-- booking_id and is_ride_dispatch flag — the FAB only opens the new
-- shared popup when is_ride_dispatch is true (that's the only case the
-- popup's PIN-start step is meant for; every other booking type keeps
-- its existing page link exactly as before, same "Mark Trip Complete"
-- one-tap flow it's always had). For the driver, that also means only
-- a trip offer backed by a ride_dispatch_requests row counts, even if
-- an ordinary route coincidentally has exactly one rider booked so far.
CREATE OR REPLACE FUNCTION my_ongoing_ride() RETURNS jsonb AS $$
DECLARE
  v_portal_user_id uuid := current_portal_user_id();
  v_today date := (now() AT TIME ZONE 'Asia/Karachi')::date;
  v_driver_trip record; v_rider_booking record; v_sole_booking_id uuid; v_is_dispatch boolean;
BEGIN
  IF v_portal_user_id IS NULL THEN RETURN NULL; END IF;

  SELECT o.id AS trip_offer_id, o.origin, o.destination INTO v_driver_trip
  FROM vehicle_trip_offers o JOIN vehicles v ON v.id = o.vehicle_id
  WHERE v.portal_user_id = v_portal_user_id AND o.travel_date = v_today
    AND (
      o.status = 'open'
      OR (o.status = 'closed' AND EXISTS (
        SELECT 1 FROM vehicle_trip_bookings bk WHERE bk.trip_offer_id = o.id AND bk.status IN ('confirmed', 'in_progress')
      ))
    )
  ORDER BY o.created_at DESC LIMIT 1;

  IF FOUND THEN
    v_is_dispatch := EXISTS (SELECT 1 FROM ride_dispatch_requests WHERE trip_offer_id = v_driver_trip.trip_offer_id);
    IF v_is_dispatch THEN
      SELECT id INTO v_sole_booking_id FROM vehicle_trip_bookings WHERE trip_offer_id = v_driver_trip.trip_offer_id AND status IN ('confirmed', 'in_progress') LIMIT 1;
    END IF;
    RETURN jsonb_build_object('role', 'driver', 'trip_offer_id', v_driver_trip.trip_offer_id, 'booking_id', v_sole_booking_id, 'is_ride_dispatch', v_is_dispatch,
      'label', v_driver_trip.origin || ' → ' || v_driver_trip.destination,
      'link', '/portal/my-vehicle/trips');
  END IF;

  SELECT b.id AS booking_id, o.origin, o.destination INTO v_rider_booking
  FROM vehicle_trip_bookings b JOIN vehicle_trip_offers o ON o.id = b.trip_offer_id
  WHERE b.portal_user_id = v_portal_user_id AND b.status IN ('confirmed', 'in_progress') AND o.travel_date = v_today
  ORDER BY b.created_at DESC LIMIT 1;

  IF FOUND THEN
    v_is_dispatch := EXISTS (SELECT 1 FROM ride_dispatch_requests WHERE trip_offer_id = (SELECT trip_offer_id FROM vehicle_trip_bookings WHERE id = v_rider_booking.booking_id));
    RETURN jsonb_build_object('role', 'rider', 'booking_id', v_rider_booking.booking_id, 'is_ride_dispatch', v_is_dispatch,
      'label', v_rider_booking.origin || ' → ' || v_rider_booking.destination,
      'link', '/portal/marketplace/trip/' || v_rider_booking.booking_id);
  END IF;

  RETURN NULL;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public;
