// The interface dictionary, shipped with the code.
//
// This is deliberately NOT in the database. A village that buys this system
// gets a fully Urdu interface on the day it is installed, and every screen
// built afterwards arrives already translated — neither of which is true if
// translations only exist in a settings table somebody has to fill in.
//
// A village that dislikes a particular word overrides just that key, through
// Settings → Wording. Those overrides live in the ui_overrides table and are
// merged over the top of this at runtime (see LocaleProvider), so upgrades keep
// working and only the handful of changed strings are stored.
//
// Keys are dotted and grouped by area. Add English and Urdu together — a key
// with no Urdu falls back to English, which is visible and fixable, rather than
// showing a raw key to a villager.

