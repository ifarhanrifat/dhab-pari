'use client'

// Commercial ilan approval — real ask, 2026-10-16: "why not put this
// option in already existing alerts and ilan" rather than its own
// separate sidebar page. Lives inside /admin/notifications (Alerts &
// Appeals) now, matching that page's own stated principle ("one
// control room, not scattered approve buttons on every feature's own
// page") -- a self-contained component rather than merged state, so it
// can't collide with that page's own `pending`/`loading`/`actionId`.

import { useEffect, useState, useCallback } from 'react'
import { Megaphone, CheckCircle2, XCircle, Pencil, Bot } from 'lucide-react'
import { toast } from 'sonner'
import { createClient } from '@/lib/supabase/client'
import { friendlyError } from '@/lib/errors'
import { useLocale } from '@/lib/i18n/LocaleProvider'
import { LoadingDots } from '@/components/shared/LoadingDots'

interface Ilan {
  id: string; placement: string; title_ur: string; title_en: string | null; body_ur: string; body_en: string | null
  price_pkr: number; starts_at: string; ends_at: string; target_tenant_ids: string[]
  contact_mobile: string | null; is_auto_generated: boolean; status: string; rejection_reason: string | null
}

function fmt(n: number) { return Number(n ?? 0).toLocaleString(undefined, { maximumFractionDigits: 0 }) }

export function IlanApprovalSection() {
  const { t, isUrdu } = useLocale()
  const supabase = createClient()
  const [loading, setLoading] = useState(true)
  const [pending, setPending] = useState<Ilan[]>([])
  const [history, setHistory] = useState<Ilan[]>([])
  const [actionId, setActionId] = useState<string | null>(null)
  const [editingId, setEditingId] = useState<string | null>(null)
  const [editTitleUr, setEditTitleUr] = useState('')
  const [editBodyUr, setEditBodyUr] = useState('')

  const load = useCallback(async () => {
    const [{ data: p }, { data: h }] = await Promise.all([
      supabase.from('commercial_ilans').select('id, placement, title_ur, title_en, body_ur, body_en, price_pkr, starts_at, ends_at, target_tenant_ids, contact_mobile, is_auto_generated, status, rejection_reason')
        .eq('status', 'pending_approval').order('created_at', { ascending: true }),
      supabase.from('commercial_ilans').select('id, placement, title_ur, title_en, body_ur, body_en, price_pkr, starts_at, ends_at, target_tenant_ids, contact_mobile, is_auto_generated, status, rejection_reason')
        .neq('status', 'pending_approval').order('created_at', { ascending: false }).limit(30),
    ])
    setPending((p ?? []) as Ilan[])
    setHistory((h ?? []) as Ilan[])
    setLoading(false)
  }, [supabase])

  useEffect(() => { load() }, [load])

  const startEdit = (ilan: Ilan) => {
    setEditingId(ilan.id)
    setEditTitleUr(ilan.title_ur)
    setEditBodyUr(ilan.body_ur)
  }

  const approve = async (ilan: Ilan) => {
    setActionId(ilan.id)
    const { error } = await supabase.rpc('committee_approve_ilan', {
      p_ilan_id: ilan.id,
      p_edited_title_ur: editingId === ilan.id ? editTitleUr : null,
      p_edited_body_ur: editingId === ilan.id ? editBodyUr : null,
    })
    setActionId(null)
    if (error) { toast.error(friendlyError(error, undefined, isUrdu)); return }
    toast.success(t('il.committeeApproved'))
    setEditingId(null)
    load()
  }
  const reject = async (id: string) => {
    const reason = window.prompt(t('il.rejectReasonPrompt')) ?? ''
    setActionId(id)
    const { error } = await supabase.rpc('committee_reject_ilan', { p_ilan_id: id, p_reason: reason || null })
    setActionId(null)
    if (error) { toast.error(friendlyError(error, undefined, isUrdu)); return }
    toast.success(t('il.committeeRejected'))
    load()
  }

  if (loading) return <div className="text-center py-8"><LoadingDots /></div>

  return (
    <div dir={isUrdu ? 'rtl' : 'ltr'} className="space-y-5">
      <div>
        <h2 className="font-heading text-[22px] font-bold text-dp-primary flex items-center gap-2"><Megaphone size={20} /> {t('il.adminHeading')}</h2>
        <p className="text-dp-on-surface-variant text-[13px] font-sans mt-0.5">{t('il.adminHint')}</p>
      </div>

      <div>
        <h3 className="font-sans text-[15px] font-bold text-dp-on-surface mb-2">{t('il.pendingHeading')}</h3>
        {pending.length === 0 ? (
          <p className="text-dp-on-surface-variant text-[13.5px] font-sans">{t('pf.noPendingIlans')}</p>
        ) : (
          <div className="space-y-2">
            {pending.map((ilan) => (
              <div key={ilan.id} className="bg-white rounded-lg border border-dp-outline-variant p-4">
                <div className="flex items-start gap-3">
                  <div className="flex-1 min-w-0">
                    {ilan.is_auto_generated && (
                      <span className="inline-flex items-center gap-1 text-[11px] font-bold text-dp-secondary bg-dp-secondary-container/30 px-2 py-0.5 rounded-full mb-1.5">
                        <Bot size={11} /> {t('il.autoGeneratedBadge')}
                      </span>
                    )}
                    {editingId === ilan.id ? (
                      <div className="space-y-2">
                        <input value={editTitleUr} onChange={(e) => setEditTitleUr(e.target.value)} dir="rtl" className="w-full px-2.5 py-1.5 border border-dp-outline-variant rounded-lg font-sans text-[13.5px]" />
                        <textarea value={editBodyUr} onChange={(e) => setEditBodyUr(e.target.value)} dir="rtl" rows={2} className="w-full px-2.5 py-1.5 border border-dp-outline-variant rounded-lg font-sans text-[13px] resize-none" />
                      </div>
                    ) : (
                      <>
                        <p className="font-sans font-bold text-[14.5px]" dir="rtl">{ilan.title_ur}</p>
                        <p className="font-sans text-[13px] text-dp-on-surface-variant mt-0.5" dir="rtl">{ilan.body_ur}</p>
                      </>
                    )}
                    <p className="font-sans text-[12px] text-dp-on-surface-variant mt-1.5">
                      {ilan.placement.replace('_', ' ')} · {ilan.target_tenant_ids.length} {t('il.villagesLabel')} · ₨{fmt(ilan.price_pkr)} · {new Date(ilan.starts_at).toLocaleString()} → {new Date(ilan.ends_at).toLocaleString()}
                      {ilan.contact_mobile ? ` · ${ilan.contact_mobile}` : ''}
                    </p>
                  </div>
                  <div className="flex items-center gap-1.5 shrink-0">
                    {!ilan.is_auto_generated && editingId !== ilan.id && (
                      <button onClick={() => startEdit(ilan)} className="p-1.5 rounded-lg border border-dp-outline-variant text-dp-on-surface-variant cursor-pointer" title={t('il.editBeforeApproving')}>
                        <Pencil size={14} />
                      </button>
                    )}
                    <button onClick={() => reject(ilan.id)} disabled={actionId === ilan.id} className="flex items-center gap-1 px-2.5 py-1.5 rounded-lg border border-dp-outline-variant text-dp-error font-sans text-[12.5px] font-semibold cursor-pointer disabled:opacity-50">
                      <XCircle size={14} /> {t('pf.rejectBtn')}
                    </button>
                    <button onClick={() => approve(ilan)} disabled={actionId === ilan.id} className="flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-dp-primary text-white font-sans text-[12.5px] font-semibold cursor-pointer disabled:opacity-50">
                      <CheckCircle2 size={14} /> {t('il.approveCashReceivedBtn')}
                    </button>
                  </div>
                </div>
              </div>
            ))}
          </div>
        )}
      </div>

      <div>
        <h3 className="font-sans text-[15px] font-bold text-dp-on-surface mb-2">{t('il.historyHeading')}</h3>
        {history.length === 0 ? (
          <p className="text-dp-on-surface-variant text-[13.5px] font-sans">{t('il.noIlansYet')}</p>
        ) : (
          <div className="bg-white rounded-lg border border-dp-outline-variant divide-y divide-dp-outline-variant">
            {history.map((ilan) => (
              <div key={ilan.id} className="p-3.5 flex items-center justify-between gap-3">
                <div className="min-w-0">
                  <p className="font-sans text-[13px] font-semibold" dir="rtl">{ilan.title_ur}</p>
                  <p className="font-sans text-[11px] text-dp-on-surface-variant mt-0.5">₨{fmt(ilan.price_pkr)} · {ilan.rejection_reason ?? ''}</p>
                </div>
                <span className={`shrink-0 px-2 py-0.5 rounded-full text-[11px] font-bold ${ilan.status === 'approved' ? 'bg-green-100 text-green-800' : ilan.status === 'rejected' ? 'bg-red-100 text-red-800' : 'bg-gray-100 text-gray-600'}`}>
                  {ilan.status === 'approved' ? t('il.statusApproved') : ilan.status === 'rejected' ? t('il.statusRejected') : t('il.statusCancelled')}
                </span>
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  )
}
